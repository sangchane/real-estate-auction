-- 매각물건명세서 PDF 원본을 보관한다 — 사용자가 원문을 직접 확인할 수 있게 (권리분석 화면).
--
-- 왜 필요한가: 파서가 읽은 값(임차인·보증금·전입일)을 사용자가 검증할 방법이 없었다. 명세서는
-- 열람 창(기일 1주 전~기일)이 닫히면 **다시 못 받으므로**(WP-11 §4-3), 그때 화면에서 원문을
-- 보여주려면 받을 때 남겨두는 수밖에 없다.
--
-- **개인정보 판단**: PDF에는 점유자 성명(007로 원문 저장 허용)뿐 아니라 자유서술 3란의
-- **제3자 실명**(신고인·가등기권자)이 들어 있다. 006은 그 원문을 저장하지 않기로 결정했는데,
-- 그 사유는 "정규식 마스킹이 양방향으로 실패했다"였고 선택지는 **"원문 그대로 저장하거나,
-- 아예 저장하지 않거나"** 였다. PDF는 가공할 수 없으므로 전자에 해당한다.
-- 006이 원문을 버릴 수 있었던 것은 그 필드가 열람 창 밖에서도 재수집되기 때문인데,
-- PDF는 그렇지 않다 — 그래서 판단이 갈린다.
--
-- **보유기간으로 통제한다** (017과 같은 형식): 배당종결(결과코드 015) 사건은 점유자 성명을
-- 지울 때 PDF도 함께 지운다. 성명만 지우고 PDF를 남기면 NF-03이 무의미해진다.
--
-- 크기: 실측 90KB 안팎(2025타경103032 94,881바이트 / 2024타경149215 90,109바이트).
-- PDF는 이미 압축된 형식이라 TOAST 압축이 거의 듣지 않는다 — 명세서 4,258건 전량이면 약 380MB,
-- 현재 DB 6.2GB 대비 6% 증가다. 저장 대상을 열람 창 안에서 받은 것으로 한정하므로 실제로는
-- 이보다 작다.
ALTER TABLE auction_item_notice
    ADD COLUMN IF NOT EXISTS pdf_bytes BYTEA,
    ADD COLUMN IF NOT EXISTS pdf_fetched_at TIMESTAMPTZ;

COMMENT ON COLUMN auction_item_notice.pdf_bytes IS
    '매각물건명세서 PDF 원본. 화면에서 원문 확인용. 배당종결 마스킹 시 함께 지운다';
COMMENT ON COLUMN auction_item_notice.pdf_fetched_at IS
    'PDF를 받은 시각. NULL 이면 못 받았거나 019 이전에 스캔한 명세서다';
