-- 점유자 표 영역의 텍스트 레이어 원문을 보관한다 — 재파싱을 위해 (WP-11 §4-27·§4-29).
--
-- 왜 필요한가: 점유자 표는 열람 창(기일 1주 전~기일)에만 열리고 기일이 지나면 영구 소실이다
-- (§4-3). 그래서 파서를 고쳐도 **이미 지나간 문서는 다시 파싱할 방법이 없다** — 016이 배당요구
-- 칸 하나에 대해 겪은 문제와 같고, 지금 §4-27(동일인 갈림)·§4-29(행 뭉침)를 고치려는데 검증할
-- 과거 표본이 없다. 원문을 남겨두면 재수집 없이 몇 번이든 다시 파싱할 수 있다.
--
-- **페이지 전체가 아니라 점유자 표 영역만 담는다.** 점유자 성명은 원문 저장이 허용돼 있지만
-- (007, 사용자 결정 2026-07-30), 자유서술 3란(인수권리·지상권·비고)은 다르다 — 거기엔
-- **제3자**(신고인·가등기권자) 실명이 섞여 있어 원문을 아예 저장하지 않기로 했다(006).
-- 페이지를 통째로 담으면 그 결정이 뒤집힌다. 표 영역만 담으면 새로 저장되는 개인정보가
-- 없다 — 그 안의 성명은 이미 tenant_name에 있는 것과 같다.
--
-- **012 마스킹과 같은 시점에 함께 지운다.** 이건 공개 여부가 아니라 보유기간 규칙이다 —
-- 성명만 지우고 원문을 남기면 지운 성명이 원문에 그대로 남아 NF-03(배당종결 후 72시간 내
-- 마스킹)이 무의미해진다.
--
-- 크기: 조밀 JSON 기준 쪽당 49KB이고 TOAST 압축 후 8KB다(픽스처 11종 실측). 명세서 4,183건 ×
-- 2쪽 추정 64MB로, 현재 DB 6.2GB의 1% 수준이다.
--
-- 소급 적용은 없다. 이 컬럼이 NULL 인 것은 두 가지를 뜻한다 — 배포 이전에 스캔했거나,
-- 배포 이후이지만 마스킹으로 지워졌거나. 둘의 구분은 masked_at 으로 한다.
ALTER TABLE auction_item_notice
    ADD COLUMN IF NOT EXISTS tenant_text_region JSONB;

COMMENT ON COLUMN auction_item_notice.tenant_text_region IS
    '점유자 표 영역의 텍스트 레이어 원문(가공 없음, 쪽별 라인 배열). 재파싱용. 배당종결 마스킹 시 함께 지운다';
